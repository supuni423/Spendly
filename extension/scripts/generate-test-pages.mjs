// Regenerates extension/test-page/ (the "Fake Mall" demo storefronts) from
// backend/sources/mock/catalog.json — the same file the backend's mock
// price-comparison sources load. Keeping both sides reading one file means
// the demo pages you click through and the prices Spendly actually
// computes can never drift apart.
//
// Run with: npm run generate:test-pages

import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const extensionRoot = join(__dirname, "..");
const catalogPath = join(extensionRoot, "..", "backend", "sources", "mock", "catalog.json");
const testPageRoot = join(extensionRoot, "test-page");

const catalog = JSON.parse(readFileSync(catalogPath, "utf-8"));

const GRADIENTS = [
  ["#ffdde1", "#ee9ca7"],
  ["#d7e3fc", "#a0c4ff"],
  ["#e2ece9", "#b8c6db"],
  ["#fceabb", "#f8b500"],
  ["#d4fc79", "#96e6a1"],
  ["#e0c3fc", "#8ec5fc"],
  ["#ffe8d6", "#ffb997"],
  ["#cdeffd", "#90d7f7"],
  ["#f6d365", "#fda085"],
  ["#a1c4fd", "#c2e9fb"],
  ["#fbc2eb", "#a6c1ee"],
  ["#84fab0", "#8fd3f4"],
  ["#e6dee9", "#a3a7ab"],
  ["#fddb92", "#d1fdff"],
];

function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function formatPrice(amount) {
  return `Rs. ${Math.round(amount).toLocaleString("en-US")}`;
}

function gradientFor(index) {
  return GRADIENTS[index % GRADIENTS.length];
}

// --- Build the generated thumbnail CSS (one gradient class per category, one per store) ---

const categoryNames = Object.keys(catalog.category_icons);
const storeKeys = Object.keys(catalog.stores);

let css = "/* Auto-generated by scripts/generate-test-pages.mjs — do not hand-edit. */\n\n";
categoryNames.forEach((category, i) => {
  const [c1, c2] = gradientFor(i);
  css += `.thumb-${slugify(category)} {\n  background: linear-gradient(135deg, ${c1}, ${c2});\n}\n\n`;
});
storeKeys.forEach((storeKey, i) => {
  const [c1, c2] = gradientFor(categoryNames.length + i);
  css += `.thumb-store-${storeKey} {\n  background: linear-gradient(135deg, ${c1}, ${c2});\n}\n\n`;
});
writeFileSync(join(testPageRoot, "generated-thumbs.css"), css);

// --- Build per-store product lists ---

const productsByStore = Object.fromEntries(storeKeys.map((key) => [key, []]));
for (const product of catalog.products) {
  for (const [storeKey, price] of Object.entries(product.prices)) {
    productsByStore[storeKey].push({ ...product, price, slug: slugify(product.name) });
  }
}
for (const storeKey of storeKeys) {
  productsByStore[storeKey].sort(
    (a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name)
  );
}

// --- Clean slate: wipe and recreate every store directory ---

for (const storeKey of storeKeys) {
  rmSync(join(testPageRoot, storeKey), { recursive: true, force: true });
  mkdirSync(join(testPageRoot, storeKey, "products"), { recursive: true });
}

function productCardHtml(product, href) {
  const categorySlug = slugify(product.category);
  return `      <a class="product-card" href="${href}">
        <div class="product-thumb thumb-${categorySlug}">${catalog.category_icons[product.category] ?? "🛒"}</div>
        <p class="category-tag">${product.category}</p>
        <h2>${product.name}</h2>
        <p>${formatPrice(product.price)}</p>
      </a>`;
}

function productPageHtml(product, store, storeLabel) {
  const categorySlug = slugify(product.category);
  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "Product",
    name: product.name,
    brand: { "@type": "Brand", name: product.brand ?? storeLabel },
    category: product.category,
    sku: product.sku,
    offers: { "@type": "Offer", price: String(Math.round(product.price)), priceCurrency: "LKR" },
  };
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <title>${product.name} — ${storeLabel}</title>
    <meta property="og:type" content="product" />
    <meta property="og:title" content="${product.name}" />
    <meta property="og:price:amount" content="${Math.round(product.price)}" />
    <meta property="og:price:currency" content="LKR" />
    <script type="application/ld+json">
      ${JSON.stringify(jsonLd, null, 2)}
    </script>
    <link rel="stylesheet" href="../../store.css" />
    <link rel="stylesheet" href="../../generated-thumbs.css" />
  </head>
  <body>
    <a class="back-link" href="../index.html">&larr; Back to ${storeLabel}</a>
    <div class="product-page">
      <div class="product-thumb thumb-${categorySlug}">${catalog.category_icons[product.category] ?? "🛒"}</div>
      <p class="category-tag">${product.category}</p>
      <h1>${product.name}</h1>
      <p class="price">${formatPrice(product.price)}</p>
      <p class="muted">Sold by ${storeLabel}.</p>
    </div>
  </body>
</html>
`;
}

function storeIndexHtml(storeKey, store) {
  const products = productsByStore[storeKey];
  const cards = products
    .map((p) => productCardHtml(p, `products/${p.slug}.html`))
    .join("\n");
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <title>${store.label}</title>
    <link rel="stylesheet" href="../store.css" />
    <link rel="stylesheet" href="../generated-thumbs.css" />
  </head>
  <body>
    <a class="back-link" href="../index.html">&larr; Back to the mall</a>
    <header class="store-header">
      <h1>${store.label}</h1>
      <p>${store.tagline}.</p>
    </header>
    <div class="store-search">
      <input type="search" id="product-search" placeholder="Search ${store.label}…" autocomplete="off" />
    </div>
    <p id="search-empty" class="search-empty" hidden>No products match your search.</p>
    <div class="product-grid" id="product-grid">
${cards}
    </div>
    <script>
      (function () {
        var input = document.getElementById("product-search");
        var cards = Array.prototype.slice.call(
          document.querySelectorAll("#product-grid .product-card")
        );
        var empty = document.getElementById("search-empty");
        input.addEventListener("input", function () {
          var query = input.value.trim().toLowerCase();
          var visible = 0;
          cards.forEach(function (card) {
            var matches = !query || card.textContent.toLowerCase().indexOf(query) !== -1;
            card.hidden = !matches;
            if (matches) visible++;
          });
          empty.hidden = visible > 0;
        });
      })();
    </script>
  </body>
</html>
`;
}

for (const [storeKey, store] of Object.entries(catalog.stores)) {
  writeFileSync(join(testPageRoot, storeKey, "index.html"), storeIndexHtml(storeKey, store));
  for (const product of productsByStore[storeKey]) {
    writeFileSync(
      join(testPageRoot, storeKey, "products", `${product.slug}.html`),
      productPageHtml(product, storeKey, store.label)
    );
  }
}

// --- Top-level mall directory ---

const storeCards = Object.entries(catalog.stores)
  .map(
    ([storeKey, store]) => `      <a class="product-card" href="${storeKey}/index.html">
        <div class="product-thumb thumb-store-${storeKey}">${store.icon}</div>
        <h2>${store.label}</h2>
        <p>${store.tagline}</p>
      </a>`
  )
  .join("\n");

writeFileSync(
  join(testPageRoot, "index.html"),
  `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <title>Market Square</title>
    <link rel="stylesheet" href="store.css" />
    <link rel="stylesheet" href="generated-thumbs.css" />
  </head>
  <body>
    <header class="store-header">
      <h1>Market Square</h1>
      <p>Five stores under one roof. Pick one to start browsing.</p>
    </header>
    <div class="product-grid">
${storeCards}
    </div>
  </body>
</html>
`
);

const totalProducts = catalog.products.length;
const totalListings = Object.values(productsByStore).reduce((sum, list) => sum + list.length, 0);
console.log(
  `Generated ${storeKeys.length} stores, ${totalProducts} unique products, ${totalListings} product pages.`
);
